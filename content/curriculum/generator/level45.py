RBY = {r["id"]: r for r in recipes}


def RL(id_, title, summary, goals, concepts, synth, mins, diff, recipe_ids, steps=None, theory=None, extra_ex=None,
       prereq=None, unverified=False, note=None):
    ex = []
    for rid in recipe_ids:
        r = RBY[rid]
        ex.append(EX("sound-match", f"Повтори: {r['name']}", f"Собери звук по слуху и сравни с эталоном в режиме A/B. {r['summary']}", r["patch"]))
    ex += extra_ex or []
    les = L(id_, title, summary, goals, concepts, synth, mins, diff, steps or [], ex, prereq=prereq, theory=theory,
            unverified=unverified, note=note)
    les["recipeIds"] = recipe_ids
    return les

